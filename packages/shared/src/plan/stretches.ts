/**
 * Look a drill or stretch up by name across every library, the core warm-up and
 * cool-down routines plus the wave-5 expansions. Used by the detail view.
 */
export function findDrill(name?: string): Drill | undefined {
	if (!name) return undefined;
	return [
		...WARMUP_DRILLS,
		...COOLDOWN_STRETCHES,
		...EXTRA_STRETCHES,
		...STRETCHES,
		...DYNAMIC_DRILLS,
		...RECOVERY_DRILLS,
	].find((d) => d.name === name);
}
